/**
 * Command Center — the dashboard's landing page.
 *
 * Server Component. Fetches the most recent test matrices and bug
 * reports from Supabase in parallel, with tight column selection so
 * payloads stay small even as the tables grow. Renders four stat
 * cards plus two data panels (matrices + failures).
 *
 * If Supabase env vars aren't configured yet, the page renders a
 * "setup required" state instead of crashing — handy for the very
 * first Render deploy before secrets are wired up.
 */

import { formatDistanceToNow, format } from 'date-fns';
import {
  ClipboardList,
  Bug,
  AlertTriangle,
  Clock3,
  ExternalLink,
  CheckCircle2,
  Settings2,
  Activity,
} from 'lucide-react';

import { getSupabaseClient, isSupabaseConfigured } from '@/lib/supabase';
import type {
  TestMatrixRow,
  BugReportRow,
  DashboardStats,
} from '@/lib/types';

// Always render fresh per request — QA data is live and cheap to re-query.
export const dynamic = 'force-dynamic';

/* ------------------------------------------------------------------ */
/*  Data loading                                                       */
/* ------------------------------------------------------------------ */

interface CommandCenterData {
  stats: DashboardStats;
  recentMatrices: TestMatrixRow[];
  recentBugReports: BugReportRow[];
  error?: string;
}

async function loadCommandCenterData(): Promise<CommandCenterData> {
  const empty: CommandCenterData = {
    stats: {
      totalMatrices: 0,
      totalCases: 0,
      totalBugReports: 0,
      lastRunAt: null,
    },
    recentMatrices: [],
    recentBugReports: [],
  };

  const supabase = getSupabaseClient();
  if (!supabase) return empty;

  // Parallelized lean queries — only the columns we render, with head
  // counts to get totals without streaming every row.
  const [matricesRes, bugReportsRes, matrixCountRes, bugCountRes] = await Promise.all([
    supabase
      .from('test_matrices')
      .select('id, source_url, page_title, captured_at, generated_at, total_cases')
      .order('generated_at', { ascending: false })
      .limit(5),
    supabase
      .from('bug_reports')
      .select(
        'id, test_id, test_title, describe_path, source_spec, status, expected, actual, duration_ms, run_at',
      )
      .order('run_at', { ascending: false })
      .limit(10),
    supabase
      .from('test_matrices')
      .select('total_cases', { count: 'exact', head: false })
      .limit(1000),
    supabase
      .from('bug_reports')
      .select('id', { count: 'exact', head: true }),
  ]);

  const firstError =
    matricesRes.error ||
    bugReportsRes.error ||
    matrixCountRes.error ||
    bugCountRes.error;
  if (firstError) {
    return { ...empty, error: firstError.message };
  }

  const recentMatrices = (matricesRes.data ?? []) as TestMatrixRow[];
  const recentBugReports = (bugReportsRes.data ?? []) as BugReportRow[];

  const totalCases =
    (matrixCountRes.data ?? []).reduce(
      (sum: number, row: { total_cases: number | null }) =>
        sum + (row.total_cases ?? 0),
      0,
    ) ?? 0;

  const lastRunAt = recentBugReports[0]?.run_at ?? recentMatrices[0]?.generated_at ?? null;

  return {
    stats: {
      totalMatrices: matrixCountRes.count ?? recentMatrices.length,
      totalCases,
      totalBugReports: bugCountRes.count ?? recentBugReports.length,
      lastRunAt,
    },
    recentMatrices,
    recentBugReports,
  };
}

/* ------------------------------------------------------------------ */
/*  Page                                                               */
/* ------------------------------------------------------------------ */

export default async function CommandCenterPage() {
  const configured = isSupabaseConfigured();
  const data = configured
    ? await loadCommandCenterData()
    : ({
        stats: {
          totalMatrices: 0,
          totalCases: 0,
          totalBugReports: 0,
          lastRunAt: null,
        },
        recentMatrices: [],
        recentBugReports: [],
      } as CommandCenterData);

  return (
    <div className="mx-auto w-full max-w-7xl px-6 py-10 sm:px-10">
      <PageHeader />

      {!configured && <SetupRequiredBanner />}
      {configured && data.error && <ErrorBanner message={data.error} />}

      <section className="mt-8 grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <StatCard
          label="Test Matrices"
          value={data.stats.totalMatrices.toLocaleString()}
          caption="Generated by the CLI"
          icon={ClipboardList}
          accent="emerald"
        />
        <StatCard
          label="Total Cases"
          value={data.stats.totalCases.toLocaleString()}
          caption="Across every matrix"
          icon={Activity}
          accent="cyan"
        />
        <StatCard
          label="Bug Reports"
          value={data.stats.totalBugReports.toLocaleString()}
          caption="Failing Playwright runs"
          icon={Bug}
          accent="rose"
        />
        <StatCard
          label="Last Activity"
          value={
            data.stats.lastRunAt
              ? formatDistanceToNow(new Date(data.stats.lastRunAt), {
                  addSuffix: true,
                })
              : '—'
          }
          caption={
            data.stats.lastRunAt
              ? format(new Date(data.stats.lastRunAt), 'PPpp')
              : 'No CLI runs recorded yet'
          }
          icon={Clock3}
          accent="amber"
        />
      </section>

      <section className="mt-10 grid grid-cols-1 gap-6 xl:grid-cols-5">
        <Panel
          className="xl:col-span-3"
          title="Recent Test Matrices"
          subtitle="The five most recent matrices pushed by the CLI."
          icon={ClipboardList}
        >
          {data.recentMatrices.length === 0 ? (
            <EmptyState
              icon={ClipboardList}
              title="No test matrices yet"
              body="Run `autoqa generate-matrix --push-supabase` to send your first matrix here."
            />
          ) : (
            <MatricesTable rows={data.recentMatrices} />
          )}
        </Panel>

        <Panel
          className="xl:col-span-2"
          title="Recent Bug Reports"
          subtitle="The ten most recent Playwright failures."
          icon={Bug}
        >
          {data.recentBugReports.length === 0 ? (
            <EmptyState
              icon={CheckCircle2}
              title="No bug reports"
              body="No failures on record. Run `autoqa run --push-supabase` after a test run to populate this panel."
            />
          ) : (
            <BugReportsList rows={data.recentBugReports} />
          )}
        </Panel>
      </section>
    </div>
  );
}

