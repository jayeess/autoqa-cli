interface StatCardProps {
  label: string;
  value: string;
  caption: string;
  icon: React.ComponentType<React.SVGProps<SVGSVGElement>>;
  accent: 'emerald' | 'cyan' | 'rose' | 'amber';
}

function StatCard({ label, value, caption, icon: Icon, accent }: StatCardProps) {
  const accents: Record<StatCardProps['accent'], string> = {
    emerald: 'bg-emerald-500/10 text-emerald-300 ring-emerald-500/20',
    cyan: 'bg-cyan-500/10 text-cyan-300 ring-cyan-500/20',
    rose: 'bg-rose-500/10 text-rose-300 ring-rose-500/20',
    amber: 'bg-amber-500/10 text-amber-300 ring-amber-500/20',
  };
  return (
    <div className="rounded-xl border border-slate-800 bg-slate-900/40 p-5 transition-colors hover:border-slate-700">
      <div className="flex items-center justify-between">
        <span className="text-xs font-medium uppercase tracking-wider text-slate-500">
          {label}
        </span>
        <span
          className={`inline-flex h-8 w-8 items-center justify-center rounded-lg ring-1 ${accents[accent]}`}
        >
          <Icon className="h-4 w-4" />
        </span>
      </div>
      <p className="mt-4 text-2xl font-semibold tracking-tight text-slate-50">
        {value}
      </p>
      <p className="mt-1 text-xs text-slate-500">{caption}</p>
    </div>
  );
}

interface PanelProps {
  title: string;
  subtitle: string;
  icon: React.ComponentType<React.SVGProps<SVGSVGElement>>;
  className?: string;
  children: React.ReactNode;
}

function Panel({ title, subtitle, icon: Icon, className, children }: PanelProps) {
  return (
    <section
      className={`overflow-hidden rounded-xl border border-slate-800 bg-slate-900/40 ${className ?? ''}`}
    >
      <header className="flex items-start justify-between border-b border-slate-800 px-5 py-4">
        <div>
          <h2 className="flex items-center gap-2 text-sm font-semibold text-slate-100">
            <Icon className="h-4 w-4 text-slate-400" />
            {title}
          </h2>
          <p className="mt-0.5 text-xs text-slate-500">{subtitle}</p>
        </div>
      </header>
      <div className="p-5">{children}</div>
    </section>
  );
}

function MatricesTable({ rows }: { rows: TestMatrixRow[] }) {
  return (
    <div className="overflow-x-auto">
      <table className="w-full text-left text-sm">
        <thead>
          <tr className="border-b border-slate-800 text-xs uppercase tracking-wider text-slate-500">
            <th className="pb-3 pr-4 font-medium">Page</th>
            <th className="pb-3 pr-4 font-medium">Cases</th>
            <th className="pb-3 pr-4 font-medium">Generated</th>
            <th className="pb-3 font-medium" />
          </tr>
        </thead>
        <tbody>
          {rows.map((row) => {
            const host = safeHost(row.source_url);
            return (
              <tr
                key={row.id}
                className="border-b border-slate-900 last:border-b-0 hover:bg-slate-900/60"
              >
                <td className="py-3 pr-4">
                  <div className="font-medium text-slate-100">
                    {row.page_title || host || 'Untitled page'}
                  </div>
                  <div className="truncate text-xs text-slate-500">
                    {row.source_url}
                  </div>
                </td>
                <td className="py-3 pr-4">
                  <span className="inline-flex items-center rounded-md bg-emerald-500/10 px-2 py-1 text-xs font-semibold text-emerald-300 ring-1 ring-inset ring-emerald-500/20">
                    {row.total_cases}
                  </span>
                </td>
                <td className="py-3 pr-4 text-xs text-slate-400">
                  <div>
                    {formatDistanceToNow(new Date(row.generated_at), {
                      addSuffix: true,
                    })}
                  </div>
                  <div className="text-slate-600">
                    {format(new Date(row.generated_at), 'PP p')}
                  </div>
                </td>
                <td className="py-3 text-right">
                  <a
                    href={row.source_url}
                    target="_blank"
                    rel="noreferrer"
                    className="inline-flex items-center gap-1 text-xs font-medium text-slate-400 transition-colors hover:text-emerald-300"
                  >
                    Source
                    <ExternalLink className="h-3 w-3" />
                  </a>
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

function BugReportsList({ rows }: { rows: BugReportRow[] }) {
  return (
    <ol className="space-y-3">
      {rows.map((row) => (
        <li
          key={row.id}
          className="rounded-lg border border-slate-800 bg-slate-950/40 p-3 transition-colors hover:border-rose-500/40"
        >
          <div className="flex items-start justify-between gap-2">
            <div className="min-w-0">
              <div className="flex items-center gap-2">
                <StatusBadge status={row.status} />
                {row.test_id && (
                  <span className="font-mono text-[10px] font-semibold text-slate-500">
                    {row.test_id}
                  </span>
                )}
              </div>
              <p className="mt-1 truncate text-sm font-medium text-slate-100">
                {row.test_title}
              </p>
              {row.describe_path && (
                <p className="mt-0.5 truncate text-xs text-slate-500">
                  {row.describe_path}
                </p>
              )}
            </div>
            <span className="shrink-0 text-[10px] text-slate-500">
              {formatDistanceToNow(new Date(row.run_at), { addSuffix: true })}
            </span>
          </div>
          {row.actual && (
            <p className="mt-2 line-clamp-2 text-xs text-slate-400">
              <span className="font-semibold text-rose-300">Actual:</span>{' '}
              {row.actual}
            </p>
          )}
        </li>
      ))}
    </ol>
  );
}

function StatusBadge({ status }: { status: string }) {
  const map: Record<string, string> = {
    failed: 'bg-rose-500/10 text-rose-300 ring-rose-500/20',
    timedOut: 'bg-amber-500/10 text-amber-300 ring-amber-500/20',
    interrupted: 'bg-slate-500/10 text-slate-300 ring-slate-500/20',
  };
  const classes = map[status] ?? 'bg-slate-500/10 text-slate-300 ring-slate-500/20';
  return (
    <span
      className={`inline-flex items-center rounded-full px-2 py-0.5 text-[10px] font-semibold uppercase ring-1 ring-inset ${classes}`}
    >
      {status}
    </span>
  );
}

