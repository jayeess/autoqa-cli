function ErrorBanner({ message }: { message: string }) {
  return (
    <div className="mt-6 flex items-start gap-3 rounded-lg border border-rose-500/30 bg-rose-500/5 p-4">
      <AlertTriangle className="mt-0.5 h-5 w-5 shrink-0 text-rose-400" />
      <div className="text-sm text-rose-100">
        <p className="font-semibold">Supabase query failed.</p>
        <p className="mt-1 font-mono text-xs text-rose-200/80">{message}</p>
      </div>
    </div>
  );
}

function safeHost(url: string): string | null {
  try {
    return new URL(url).hostname;
  } catch {
    return null;
  }
}
